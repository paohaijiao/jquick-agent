package io.github.paohaijiao.jquick.agent.test;

import io.github.paohaijiao.jquick.agent.bootstrap.JQuickArgumentParser;
import io.github.paohaijiao.jquick.agent.core.JQuickClassContext;
import io.github.paohaijiao.jquick.agent.core.JQuickClassEnhancer;
import io.github.paohaijiao.jquick.agent.core.JQuickClassMeta;
import io.github.paohaijiao.jquick.agent.core.JQuickConfig;
import io.github.paohaijiao.jquick.agent.core.JQuickEnvironment;
import io.github.paohaijiao.jquick.agent.core.JQuickPlugin;
import io.github.paohaijiao.jquick.agent.runtime.JQuickSink;

import java.io.ByteArrayOutputStream;
import java.io.InputStream;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

/**
 * Test harness that runs the real instrumentation pipeline without a JVM agent.
 *
 * <p>A unit test cannot ask the JVM for an {@code Instrumentation}, and requiring one would push the
 * whole suite into a forked-process arrangement where failures are invisible. It does not have to:
 * the agent's own structure makes the pipeline directly callable. An enhancer is a pure function from
 * bytes to bytes, and everything the injected byte-code needs at run time is reachable through the
 * environment singleton. So the harness
 *
 * <ol>
 *   <li>builds an environment from an {@code agentArgs} string, exactly as the bootstrap does;</li>
 *   <li>initialises the plugins and collects their enhancers;</li>
 *   <li>reads a fixture class from the test classpath and runs it through the enhancer chain;</li>
 *   <li>defines the result in a fresh class loader, so the enhanced copy is a genuinely separate
 *       class and the JVM verifier — not the test — decides whether the injected byte-code is
 *       valid.</li>
 * </ol>
 *
 * <p>Step 4 is the important one. Asserting on the generated byte-code would only prove that it is
 * <em>as intended</em>; loading it proves it is <em>valid</em>, and a {@code VerifyError} is the
 * failure mode that matters in production.
 *
 * @author Martin
 */
public final class JQuickHarness {

    private final JQuickConfig config;

    private final JQuickEnvironment environment;

    private final List<JQuickClassEnhancer> enhancers = new ArrayList<JQuickClassEnhancer>();

    private final JQuickBytecodeLoader loader =
            new JQuickBytecodeLoader(JQuickHarness.class.getClassLoader());

    private JQuickHarness(JQuickConfig config, JQuickEnvironment environment) {
        this.config = config;
        this.environment = environment;
    }

    /* ================================================================== factories */

    /**
     * Installs the given plugins, keeping only those that report themselves enabled — the same filter
     * the bootstrap applies, so a test cannot accidentally exercise a capability the operator would
     * never get.
     */
    public static JQuickHarness ofPlugins(String agentArgs, JQuickPlugin... plugins) {
        JQuickHarness harness = empty(agentArgs);
        for (JQuickPlugin plugin : plugins) {
            if (!plugin.isEnabled(harness.config)) {
                continue;
            }
            plugin.initialize(harness.environment);
            harness.environment.addPlugin(plugin);
            for (JQuickClassEnhancer enhancer : plugin.enhancers()) {
                harness.environment.addEnhancer(enhancer);
                harness.enhancers.add(enhancer);
            }
        }
        return harness;
    }

    /**
     * Installs a bare environment with hand-written enhancers; used to test the emitter in isolation
     * from any capability policy.
     */
    public static JQuickHarness ofEnhancers(String agentArgs, JQuickClassEnhancer... enhancers) {
        JQuickHarness harness = empty(agentArgs);
        for (JQuickClassEnhancer enhancer : enhancers) {
            harness.environment.addEnhancer(enhancer);
            harness.enhancers.add(enhancer);
        }
        return harness;
    }

    /**
     * Registers an enhancer after construction, before any class has been loaded through the harness.
     */
    public JQuickHarness withEnhancer(JQuickClassEnhancer enhancer) {
        environment.addEnhancer(enhancer);
        enhancers.add(enhancer);
        return this;
    }

    private static JQuickHarness empty(String agentArgs) {
        // Process-wide state has to be reset: the sink and the environment singleton are deliberately
        // global, because injected byte-code can only reach a static anchor.
        JQuickEnvironment.reset();
        JQuickSink.reset();
        JQuickConfig config = JQuickConfig.of(JQuickArgumentParser.parse(agentArgs));
        JQuickEnvironment environment = JQuickEnvironment.create(config);
        JQuickEnvironment.install(environment);
        return new JQuickHarness(config, environment);
    }

    /* ================================================================== accessors */

    public JQuickEnvironment environment() {
        return environment;
    }

    public JQuickConfig config() {
        return config;
    }

    public List<JQuickClassEnhancer> enhancers() {
        return Collections.unmodifiableList(enhancers);
    }

    /* ================================================================== instrumentation */

    /**
     * Runs the class bytes through every enhancer that accepts them, threading the output of one into
     * the next so that two capabilities on the same class behave as they would in production.
     *
     * @return an object carrying both the resulting bytes and whether anything actually changed
     */
    public Enhanced enhanceReporting(byte[] original) {
        JQuickClassMeta meta = JQuickClassMeta.of(original);
        if (meta == null) {
            throw new IllegalStateException("the fixture class bytes could not be parsed");
        }
        JQuickClassContext context = new JQuickClassContext(
                meta.getClassName(), loader, original, meta, false);
        boolean changed = false;
        for (JQuickClassEnhancer enhancer : enhancers) {
            if (!enhancer.supports(context)) {
                continue;
            }
            byte[] result = enhancer.enhance(context);
            if (result != null && result.length > 0) {
                context = context.withBytes(result);
                changed = true;
            }
        }
        return new Enhanced(context.getClassBytes(), changed);
    }

    /**
     * Enhanced bytes; identical to the input when no enhancer accepted the class.
     */
    public byte[] enhance(byte[] original) {
        return enhanceReporting(original).bytes;
    }

    /**
     * Loads a fixture class from the test classpath, instruments it and defines it in a private class
     * loader.
     *
     * @param className binary name, e.g. {@code example.app.FixtureService}
     */
    public Class<?> load(String className) {
        return loader.loadEnhanced(className, this);
    }

    /**
     * Reads a class from the test classpath without instrumenting it.
     */
    public static byte[] readBytes(String className) {
        return JQuickBytecodeLoader.read(className);
    }

    /* ================================================================== nested types */

    /**
     * Outcome of an instrumentation pass.
     */
    public static final class Enhanced {

        private final byte[] bytes;

        private final boolean changed;

        Enhanced(byte[] bytes, boolean changed) {
            this.bytes = bytes;
            this.changed = changed;
        }

        public byte[] getBytes() {
            return bytes;
        }

        public boolean isChanged() {
            return changed;
        }

        public int size() {
            return bytes.length;
        }
    }

    /**
     * Defines enhanced classes in isolation from the test class loader.
     *
     * <p>The loader deliberately defines the fixture classes itself instead of delegating to its
     * parent. If it delegated, the parent's untouched copy would be found first and every test would
     * silently assert against uninstrumented code — the single most expensive mistake a suite like
     * this can make.
     */
    private static final class JQuickBytecodeLoader extends ClassLoader {

        private final List<String> defined = new ArrayList<String>();

        JQuickBytecodeLoader(ClassLoader parent) {
            super(parent);
        }

        Class<?> loadEnhanced(String className, JQuickHarness harness) {
            synchronized (getClassLoadingLock(className)) {
                Class<?> loaded = findLoadedClass(className);
                if (loaded != null) {
                    return loaded;
                }
                byte[] original = read(className);
                Enhanced enhanced = harness.enhanceReporting(original);
                if (!enhanced.isChanged()) {
                    throw new IllegalStateException("no enhancer accepted " + className
                            + "; the fixture does not match the configured selection rules");
                }
                Class<?> defined = defineClass(className, enhanced.getBytes(), 0,
                        enhanced.getBytes().length);
                this.defined.add(className);
                resolveClass(defined);
                return defined;
            }
        }

        static byte[] read(String className) {
            String resource = className.replace('.', '/') + ".class";
            InputStream stream = null;
            try {
                stream = JQuickHarness.class.getClassLoader().getResourceAsStream(resource);
                if (stream == null) {
                    throw new IllegalStateException("fixture not on the test classpath: " + resource);
                }
                ByteArrayOutputStream buffer = new ByteArrayOutputStream(4096);
                byte[] chunk = new byte[4096];
                int read;
                while ((read = stream.read(chunk)) > 0) {
                    buffer.write(chunk, 0, read);
                }
                return buffer.toByteArray();
            } catch (IllegalStateException ex) {
                throw ex;
            } catch (Exception ex) {
                throw new IllegalStateException("could not read " + resource, ex);
            } finally {
                if (stream != null) {
                    try {
                        stream.close();
                    } catch (Exception ignored) {
                        // Reading is a one-shot operation; a failed close has no consequence here.
                    }
                }
            }
        }
    }
}
